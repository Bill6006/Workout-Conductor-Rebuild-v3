import { MOVEMENT_PATTERN_IDS, type MovementPatternId } from '../movementPatterns/movementPatterns'
import type { MediaAsset, MediaManifestEntry, MediaProvenance } from './mediaSchema'

/**
 * THE production-media manifest: which asset a given exercise shows, and where
 * that asset came from.
 *
 * NEVER IMPORT THIS MODULE STATICALLY FROM A BOOT-PATH FILE. It is data, it grows
 * with the catalog, and the first-paint budget has no room for it. Reach it the
 * same way the exercise catalog is reached:
 *
 *     const { mediaRecordFor } = await import('../../catalog/media/mediaManifest')
 *
 * It is deliberately absent from `./index.ts` so that importing the media SCHEMA
 * — which several boot-path modules legitimately do — cannot drag the manifest in
 * behind it. `mediaManifest.test.ts` walks `src/` and fails if any non-test module
 * imports this one statically.
 *
 * WHAT PHASE 2 ACTUALLY SHIPS, STATED PLAINLY: zero real demonstrations. Every
 * exercise in the catalog currently resolves to a generated placeholder poster —
 * an abstract force diagram for its movement pattern, not a demonstration of the
 * exercise. That is a deliberate, documented gap, not an oversight, and closing
 * it is a decision the project owner has to make before final acceptance. See
 * `docs/media-license-register.md`. Every placeholder record carries
 * `isPlaceholder: true`, so "how big is the gap" is one query, and the Phase 8
 * acceptance test is a one-line change from the reporting test that exists today.
 *
 * THE MANIFEST DOES NOT ENUMERATE EXERCISES. A hard-coded row per exercise would
 * be a second copy of the catalog's id list, drifting the first time an id is
 * added. Instead `PRODUCTION_MEDIA` lists only the exercises that have real,
 * licensed assets, and everything else resolves to its movement pattern's
 * placeholder. Adding an exercise therefore cannot leave it with no media, and
 * cannot leave it silently counted as finished.
 */

/* ------------------------------------------------------------- placeholders */

/** The date the committed placeholder posters were generated. */
