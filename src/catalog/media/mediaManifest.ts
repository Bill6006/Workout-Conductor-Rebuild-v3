/** Path of the shared placeholder poster for a movement pattern, under the public root. */
export function placeholderPosterPath(patternId: MovementPatternId): string {
  return `${PLACEHOLDER_POSTER_DIR}/${patternId}.png`
}

/** Every placeholder poster path, in canonical pattern order. */
export const PLACEHOLDER_POSTER_PATHS: readonly string[] = MOVEMENT_PATTERN_IDS.map(placeholderPosterPath)

/** The poster asset for a movement pattern. */
export function placeholderPoster(patternId: MovementPatternId): MediaAsset {
  return {
    path: placeholderPosterPath(patternId),
    kind: 'poster',
    mimeType: PLACEHOLDER_POSTER_MIME,
    width: PLACEHOLDER_POSTER_WIDTH,
    height: PLACEHOLDER_POSTER_HEIGHT,
    byteSize: PLACEHOLDER_POSTER_BYTES[patternId],
    durationMs: null,
    provenance: PLACEHOLDER_PROVENANCE,
  }
}

/* ------------------------------------------------------------------ records */

/**
 * What an exercise has to tell the manifest about itself. A structural subset of
 * `Exercise`, restated here so that this module never imports the catalog data or
 * its schema — and so a caller can ask about an exercise it has only partly
 * loaded.
 */
export interface MediaExerciseRef {
  readonly id: string
  readonly movementPattern: MovementPatternId
  readonly productionEnabled: boolean
}

/**
 * A manifest entry plus the one fact the schema cannot carry: whether this is a
 * finished asset or a stand-in.
 *
 * `isPlaceholder` is a separate field on a wrapper rather than a field inside
 * `MediaManifestEntry` because the entry is a `z.strictObject` owned by the media
 * schema, and because "is this finished" is a project-status fact, not part of the
 * media contract. What matters is that it is impossible to hold a record without
 * also holding the answer — a placeholder can never be mistaken for a finished
 * asset by a caller that simply forgot to check a flag it never saw.
 */
export interface MediaManifestRecord {
  readonly entry: MediaManifestEntry
  readonly isPlaceholder: boolean
  /** The pattern whose shared poster is standing in; `null` for a real asset. */
  readonly placeholderPattern: MovementPatternId | null
}

/**
 * Real, licensed, exercise-specific media. EMPTY AT PHASE 2 — every row added
 * here needs a row in `docs/media-license-register.md` first, and the test suite
 * enforces the pairing in both directions.
 */
export const PRODUCTION_MEDIA: readonly MediaManifestRecord[] = []

const PRODUCTION_BY_EXERCISE_ID = new Map<string, MediaManifestRecord>(
  PRODUCTION_MEDIA.map((record) => [record.entry.exerciseId, record]),
)

/** The stand-in record for an exercise: its pattern's poster, no demonstration. */
export function placeholderRecordFor(ref: MediaExerciseRef): MediaManifestRecord {
  return {
    entry: {
      exerciseId: ref.id,
      poster: placeholderPoster(ref.movementPattern),
      demonstrations: [],
    },
    isPlaceholder: true,
    placeholderPattern: ref.movementPattern,
  }
}

/**
 * THE lookup. Real media when we have it, the movement pattern's placeholder
 * otherwise — so this never returns null and no screen has to render an empty
 * frame. What it will not do is pretend: the record says which it gave you.
 */
export function mediaRecordFor(ref: MediaExerciseRef): MediaManifestRecord {
  return PRODUCTION_BY_EXERCISE_ID.get(ref.id) ?? placeholderRecordFor(ref)
}

/** True when an exercise has a real, exercise-specific moving demonstration. */
export function hasRealDemonstration(record: MediaManifestRecord): boolean {
  return !record.isPlaceholder && record.entry.demonstrations.length > 0
}

/** The manifest for a set of exercises, in the order they were given. */
export function buildMediaManifest(refs: readonly MediaExerciseRef[]): MediaManifestRecord[] {
  return refs.map(mediaRecordFor)
}

/** The schema-shaped entries, for validation or for anything that wants the contract only. */
export function mediaManifestEntries(records: readonly MediaManifestRecord[]): MediaManifestEntry[] {
  return records.map((record) => record.entry)
}

/* ---------------------------------------------------------------- reporting */

/**
 * How much of the catalog actually has media, counted rather than estimated.
 *
 * Phase 8's acceptance gate reads this: `withPlaceholder` must be 0 for
 * production-enabled exercises. Until then the same numbers are reported so the
 * gap is visible every time the suite runs.
 */
export interface MediaCoverage {
  /** Every exercise asked about. */
  readonly total: number
  /** Those the product actually offers. Non-production exercises are exempt. */
  readonly productionEnabled: number
  /** Production-enabled exercises with a real, exercise-specific demonstration. */
  readonly withRealDemonstration: number
  /** Production-enabled exercises with a real poster but no moving demonstration. */
  readonly withRealPosterOnly: number
  /** Production-enabled exercises still showing a generated placeholder. */
  readonly withPlaceholder: number
  /** Which ones, in catalog order, so a report can name them. */
  readonly placeholderExerciseIds: readonly string[]
}

export function summariseMediaCoverage(refs: readonly MediaExerciseRef[]): MediaCoverage {
  const live = refs.filter((ref) => ref.productionEnabled)
  const placeholderExerciseIds: string[] = []
  let withRealDemonstration = 0
  let withRealPosterOnly = 0

  for (const ref of live) {
    const record = mediaRecordFor(ref)
    if (record.isPlaceholder) {
      placeholderExerciseIds.push(ref.id)
    } else if (hasRealDemonstration(record)) {
      withRealDemonstration += 1
    } else {
      withRealPosterOnly += 1
    }
  }

  return {
    total: refs.length,
    productionEnabled: live.length,
    withRealDemonstration,
    withRealPosterOnly,
    withPlaceholder: placeholderExerciseIds.length,
    placeholderExerciseIds,
  }
}

/** A one-line summary for a report, a console line, or a test failure message. */
export function describeMediaCoverage(coverage: MediaCoverage): string {
  return (
    `${coverage.withRealDemonstration}/${coverage.productionEnabled} production-enabled exercises ` +
    `have a real demonstration; ${coverage.withRealPosterOnly} have a real poster only; ` +
    `${coverage.withPlaceholder} still show a generated placeholder.`
  )
}
